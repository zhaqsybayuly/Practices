# for loop: iterate over a sequence (list, tuple, string, range, etc.)
fruits = ["apple", "banana", "cherry"]
for x in fruits:
    print(x)

# loop over a string
for letter in "hello":
    print(letter)

# loop over a range of numbers
for i in range(5):       # 0, 1, 2, 3, 4
    print(i)

# range with start, stop and step
for i in range(2, 10, 2):  # 2, 4, 6, 8
    print(i)
